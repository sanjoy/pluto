#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <vector>

#include "absl/status/status.h"
#include "absl/status/statusor.h"
#include "absl/types/span.h"

namespace pluto::llm::one_shot_memorizer {

inline constexpr size_t kReluMemoryCodeWidth = 16;
using ReluMemoryCode = std::array<float, kReluMemoryCodeWidth>;

struct ReluMemoryUnit {
  // Actual first-layer biases, interleaved as {-key[j], +key[j]}.
  // The corresponding sparse weight rows are +e_j and -e_j.
  std::vector<float> input_biases;
  // Actual output-weight column: bit b of the target token maps to +/-1.
  ReluMemoryCode output_code;
};

// A constructed, sparse, two-hidden-layer ReLU network. It is a neural
// memorization control, not GPT-2 and not an account of its trained weights.
// For each stored integer key k_i, the network literally evaluates
//   h_i(q) = ReLU(1 - sum_j[ReLU(q_j-k_ij)+ReLU(k_ij-q_j)]),
//   output(q) = sum_i h_i(q) * output_code_i.
// At integer queries, h_i is exactly 1 at its key and 0 at every other key.
// Keys are suffixes of context_window tokens, left padded with -1.
// Units are in lexicographic key order; no inference lookup table is stored.
struct ReluMemory {
  int vocabulary_size = 0;
  int eos_token_id = -1;
  size_t prompt_tokens = 0;
  size_t context_window = 0;
  std::vector<ReluMemoryUnit> units;
};

struct ReluMemoryStorageCounts {
  uint64_t first_hidden_units = 0;
  uint64_t second_hidden_units = 0;
  // Stored, corpus-dependent numeric values: first-layer biases and output
  // columns. Opposite first-layer bias pairs are explicitly stored.
  uint64_t data_dependent_float_count = 0;
  uint64_t data_dependent_bytes = 0;
  // Fixed sparse first/second-layer weights, and second-layer biases.
  // These are generated by architecture, not stored in ReluMemory.
  uint64_t fixed_sparse_weight_count = 0;
  uint64_t fixed_bias_count = 0;
  // 16 +/-1 entries for every vocabulary token, generated during decoding.
  uint64_t fixed_decoder_weight_count = 0;
};

// Sentences exclude EOS and have length >= prompt_tokens. Every next-token
// query from prompt_tokens through the sentence boundary is compiled, with
// EOS as the boundary target. Duplicate identical keys/labels are merged;
// any key with conflicting targets is rejected. Vocabulary size <= 65536,
// positive prompt_tokens/context_window, and in-range non-EOS inputs required.
absl::StatusOr<ReluMemory> BuildReluMemory(
    const std::vector<std::vector<int>>& sentences, int vocabulary_size,
    int eos_token_id, size_t prompt_tokens, size_t context_window);

// Checks metadata, finite integer key biases, padding, opposite bias pairs,
// canonical unique key order, and valid +/-1 output codes. Call after loading
// numeric weights from an artifact.
absl::Status ValidateReluMemory(const ReluMemory& model);

// Each query validates the model and all supplied tokens. Prefixes must have
// at least prompt_tokens tokens and exclude EOS. Older tokens are truncated
// to context_window; a previously unseen full prefix may match a stored
// suffix. Returns NotFound if no unit activates. Uses float32 ReLU arithmetic
// over every stored key, not a map, nearest-neighbor search, or token lookup.
absl::StatusOr<ReluMemoryCode> EvaluateReluMemory(const ReluMemory& model,
                                                  absl::Span<const int> prefix);

// Exact +/-1 codes decode by reading their bits: this equals the unique
// maximum dot product with the vocabulary's equal-norm binary codes. Codes
// outside the vocabulary are rejected. Other finite vectors use exhaustive
// float32 dot products, with ties choosing the smallest ID.
absl::StatusOr<int> DecodeReluMemoryOutput(const ReluMemory& model,
                                           const ReluMemoryCode& output);

absl::StatusOr<int> ReluMemoryNextToken(const ReluMemory& model,
                                        absl::Span<const int> prefix);

// Returns generated tokens only, including EOS on successful termination.
// If the positive limit is exhausted first, returns the partial continuation.
absl::StatusOr<std::vector<int>> ReluMemoryGreedyContinuation(
    const ReluMemory& model, absl::Span<const int> prefix,
    size_t max_new_tokens);

absl::StatusOr<ReluMemoryStorageCounts> GetReluMemoryStorageCounts(
    const ReluMemory& model);

}  // namespace pluto::llm::one_shot_memorizer
